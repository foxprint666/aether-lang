#!/usr/bin/env python
"""Publish novel-weather build A/B evidence."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("result", type=Path)
    parser.add_argument("--json-output", type=Path)
    parser.add_argument("--markdown-output", type=Path)
    args = parser.parse_args()
    payload = json.loads(args.result.read_text(encoding="utf-8"))
    report = {
        "report_version": "novel-weather-ab-evidence-v1",
        "experiment_id": payload.get("experiment_id"),
        "commit_sha": payload.get("commit_sha"),
        "algorithm": payload.get("algorithm"),
        "summary": payload["summary"],
        "build_modes": payload["build_modes"],
        "limitations": [
            "This is a deterministic local project build benchmark, not a live LLM generation study.",
            "The custom algorithm is novel within this benchmark, but not claimed as publishable ML research.",
            "The Aether path measures architecture leverage from compact states compiled into code.",
            "Token counts use a local code-token estimate, not provider billing tokens.",
        ],
    }
    if args.json_output:
        args.json_output.parent.mkdir(parents=True, exist_ok=True)
        args.json_output.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    if args.markdown_output:
        args.markdown_output.parent.mkdir(parents=True, exist_ok=True)
        args.markdown_output.write_text(markdown(report), encoding="utf-8")
    print(json.dumps(report, indent=2, sort_keys=True))
    return 0


def markdown(report: dict) -> str:
    summary = report["summary"]
    lines = [
        "# Novel Weather Algorithm A/B Report",
        "",
        f"- Algorithm: `{report['algorithm']}`.",
        f"- Raw build success: `{summary['raw_success']}`.",
        f"- Aether build success: `{summary['aether_success']}`.",
        f"- Raw MAE: `{summary['raw_mae']}`.",
        f"- Aether MAE: `{summary['aether_mae']}`.",
        f"- Raw RMSE: `{summary['raw_rmse']}`.",
        f"- Aether RMSE: `{summary['aether_rmse']}`.",
        f"- Generated token savings: `{summary['generated_token_savings_pct']}%`.",
        f"- Generated byte savings: `{summary['generated_byte_savings_pct']}%`.",
        f"- Project token delta: `{summary['project_token_delta_pct']}%`.",
        f"- Build-time savings: `{summary['build_time_savings_pct']}%`.",
        f"- Verify-time savings: `{summary['verify_time_savings_pct']}%`.",
        "",
        "## Build Modes",
        "",
    ]
    lines.extend(f"- `{key}`: {value}" for key, value in report["build_modes"].items())
    lines.extend(["", "## Limitations", ""])
    lines.extend(f"- {item}" for item in report["limitations"])
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    raise SystemExit(main())
